#!/usr/bin/env python3
"""Analyze direct guest writes to candidate MK2 object fields (+0x1A/+0x1E).

Input is opt-in *_object_writes.csv generated by the latest signal probe.
This reports actual guest memory STORE operations intercepted by DOSBox,
including the writer CS:EIP and values before and after each store.

IMPORTANT: These object identities/field meanings are not yet proven,
nor does a change of position imply one complete combat simulation step.
Guest writes through uninstrumented paths or memory aliases can be missed.

Usage:
    python scripts/analyze_mk2_object_writes.py path/to/trace_object_writes.csv
"""
from __future__ import annotations

from collections import Counter, defaultdict
import argparse
import csv
from pathlib import Path
from statistics import median


def spacing(times: list[float]) -> str:
    diffs = [b - a for a, b in zip(times, times[1:]) if b > a]
    if not diffs:
        return "n/a"
    return (f"median={median(diffs):.3f} ms; "
            f"min={min(diffs):.3f}; max={max(diffs):.3f}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("csv_file", type=Path)
    parser.add_argument("--top", type=int, default=20)
    args = parser.parse_args()

    by_writer: dict[tuple[int, int, int], list[float]] = defaultdict(list)
    by_field: dict[tuple[str, int], list[float]] = defaultdict(list)
    by_object_ptr: Counter[tuple[str, int]] = Counter()
    writer_field: Counter[tuple[str, int, int, int, int]] = Counter()
    old_new: Counter[tuple[str, int, int, int]] = Counter()
    cs_mode: Counter[str] = Counter()
    seen = 0

    with args.csv_file.open(newline="", encoding="utf-8") as stream:
        reader = csv.DictReader(stream)
        needed = {
            "emulated_ms", "object", "field_offset", "object_pointer",
            "before", "after", "writer_cs", "writer_cs_base",
            "writer_eip", "protected_mode",
        }
        if not needed.issubset(reader.fieldnames or []):
            parser.error("Missing expected _object_writes.csv columns")
        for row in reader:
            if row["object"] not in ("A", "B"):
                continue
            before, after = int(row["before"]), int(row["after"])
            if before == after:
                continue
            seen += 1
            when = float(row["emulated_ms"])
            field = (row["object"], int(row["field_offset"]))
            pc = (int(row["writer_cs"]), int(row["writer_cs_base"]),
                  int(row["writer_eip"]))
            by_writer[pc].append(when)
            by_field[field].append(when)
            by_object_ptr[(row["object"], int(row["object_pointer"]))] += 1
            writer_field[(*field, *pc)] += 1
            old_new[(row["object"], field[1], before, after)] += 1
            cs_mode["protected" if int(row["protected_mode"]) else "real"] += 1

    print(f"File: {args.csv_file.name}")
    print(f"Observed changing guest stores: {seen:,}")
    print(f"CPU mode counts: {dict(cs_mode)}")
    print("\nChanges by candidate object and field:")
    for (obj, offset), times in sorted(by_field.items()):
        print(f"  Object {obj}, +0x{offset:02X}: "
              f"{len(times):,} changes; {spacing(times)}")
    print("\nObject pointers observed during changes:")
    for (obj, ptr), count in by_object_ptr.most_common(args.top):
        print(f"  {obj} pointer=0x{ptr:08X}: {count:,}")
    print("\nGuest instructions that directly changed a monitored field:")
    for (cs, base, eip), times in sorted(
            by_writer.items(), key=lambda pair: -len(pair[1])
            )[:args.top]:
        print(f"  CS={cs:04X} base=0x{base:08X} "
              f"EIP=0x{eip:08X}: {len(times):,} field writes; "
              f"{spacing(times)}")
    print("\nWriter x field combinations:")
    for (obj, off, cs, base, eip), count in writer_field.most_common(args.top):
        print(f"  {obj} +0x{off:02X} "
              f"{cs:04X}:0x{eip:08X} base=0x{base:08X}: {count:,}")
    print("\nExample repeated old/new values:")
    for (obj, off, old, new), count in old_new.most_common(10):
        print(f"  {obj} +0x{off:02X}: {old} -> {new}: {count:,} writes")
    print("\nINTERPRETATION LIMITS")
    print("- This attributes individual observed guest STORE helpers to "
          "writer CS:EIP, unlike the prior callback correlation report.")
    print("- The watched addresses refresh at MK2 scheduler dispatches. "
          "Writes during pointer replacement before the next dispatch, "
          "aliased mappings, and uninstrumented direct memory writes "
          "can be missed.")
    print("- Some stores may touch both watched fields or represent "
          "intermediate portions of a wide write.")
    print("- Field +0x1A / +0x1E meanings and fighter identities "
          "are hypotheses pending disassembly and state validation.")
    print("- A field change near 16.65 ms is NOT proof that all physics, "
          "input and animation update at 60 Hz.")
    print("- Use a private 32-bit x86 snippet of the dominant writer to "
          "verify its code and caller/callee chain.")


if __name__ == "__main__":
    main()
